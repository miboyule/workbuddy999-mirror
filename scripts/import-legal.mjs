function blocks(markdown) {
  const chunks = markdown.trim().split(/\n\s*\n/);
  return chunks.flatMap(chunk => {
    const text = chunk.trim();
    if (/^# /.test(text) || /^发布日期：/.test(text)) return [];
    if (/^### /.test(text)) return [{ tag: 'H3', text: text.slice(4) }];
    if (/^## /.test(text)) return [{ tag: 'H2', text: text.slice(3) }];
    if (/^\d+\. /.test(text)) return [{ tag: 'OL', items: text.split(/\n(?=\d+\. )/).map(line => line.replace(/^\d+\. /, '')) }];
    if (/^- /.test(text)) return [{ tag: 'UL', items: text.split(/\n(?=- )/).map(line => line.slice(2)) }];
    return [{ tag: 'P', text }];
  });
}
